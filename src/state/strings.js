export function localizeError(lang, message) {
  if (lang !== 'hi' || typeof message !== 'string') return message;
  if (ERRORS_HI[message]) return ERRORS_HI[message];
  for (const [pattern, build] of ERROR_PATTERNS_HI) {
    const m = message.match(pattern);
    if (m) return build(m);
  }
  return message;
}
