export function t(lang, key) {
  return (strings[lang] && strings[lang][key]) ?? (strings.en[key] ?? key);
}

/** Fills {name}-style placeholders, e.g. tf('hi', 'nPending', { n: 3 }). */
export function tf(lang, key, vars = {}) {
  return t(lang, key).replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

